/**
 * generate-acl-migration.mjs
 *
 * Reads the canonical roles.defaults.json from @jurnapod/shared and generates
 * an idempotent SQL migration that seeds company-level module_roles for ALL
 * existing companies using the INSERT IGNORE ... CROSS JOIN pattern from
 * migration 0169 (acl_purchasing_suppliers_all_companies).
 *
 * Usage:
 *   node packages/db/scripts/generate-acl-migration.mjs [--output <file>]
 *
 * If --output is omitted, writes to stdout.
 *
 * Source of truth: packages/shared/src/constants/roles.defaults.json
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "../../..");

// ---------------------------------------------------------------------------
// Resolve output path
// ---------------------------------------------------------------------------

let outputPath = null;
const args = process.argv.slice(2);
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--output" && i + 1 < args.length) {
    outputPath = path.resolve(args[++i]);
  } else if (args[i] === "--help") {
    console.log("Usage: node generate-acl-migration.mjs [--output <file>]");
    process.exit(0);
  }
}

// ---------------------------------------------------------------------------
// Load canonical source of truth
// ---------------------------------------------------------------------------

const jsonPath = path.join(
  projectRoot,
  "packages/shared/src/constants/roles.defaults.json"
);

if (!fs.existsSync(jsonPath)) {
  console.error(`ERROR: roles.defaults.json not found at ${jsonPath}`);
  process.exit(1);
}

const roleDefaults = JSON.parse(fs.readFileSync(jsonPath, "utf-8"));
const roles = roleDefaults.roles;

// ---------------------------------------------------------------------------
// Group entries by (module, resource, permissionMask)
// ---------------------------------------------------------------------------

/** @type {Map<string, {module: string, resource: string, mask: number, roleCodes: string[]}>} */
const groups = new Map();

for (const [roleCode, permissions] of Object.entries(roles)) {
  for (const [moduleResource, mask] of Object.entries(permissions)) {
    const dotIndex = moduleResource.indexOf(".");
    if (dotIndex === -1) {
      console.warn(`WARNING: skipping malformed key "${moduleResource}" for role "${roleCode}"`);
      continue;
    }
    const module = moduleResource.slice(0, dotIndex);
    const resource = moduleResource.slice(dotIndex + 1);
    const key = `${module}|${resource}|${mask}`;
    const group = groups.get(key);
    if (group) {
      group.roleCodes.push(roleCode);
    } else {
      groups.set(key, { module, resource, mask, roleCodes: [roleCode] });
    }
  }
}

// ---------------------------------------------------------------------------
// Generate SQL
// ---------------------------------------------------------------------------

const sortedGroups = [...groups.values()].sort((a, b) => {
  if (a.module !== b.module) return a.module.localeCompare(b.module);
  if (a.resource !== b.resource) return a.resource.localeCompare(b.resource);
  return a.mask - b.mask;
});

const totalEntries = Object.values(roles).reduce(
  (sum, perms) => sum + Object.keys(perms).length,
  0
);

const lines = [];

lines.push("-- Copyright (c) 2026 Ahmad Faruk (Signal18 ID). All rights reserved.");
lines.push("-- Ownership: Ahmad Faruk (Signal18 ID)");
lines.push("");
lines.push("-- Migration: 0207_seed_canonical_acl_all_companies");
lines.push(
  "-- Description: Seed canonical module_roles (company-level) for ALL existing companies"
);
lines.push(
  `-- Source of truth: @jurnapod/shared/src/constants/roles.defaults.json (${totalEntries} entries, ${sortedGroups.length} groups)`
);
lines.push(
  "-- Generated by: packages/db/scripts/generate-acl-migration.mjs"
);
lines.push(
  "-- Strategy: INSERT IGNORE ... CROSS JOIN companies × roles — safe to re-run"
);
lines.push("-- Compatible with: MySQL 8.0+, MariaDB 10.2+");
lines.push("");

// ---------------------------------------------------------------------------
// Step 1: Ensure all modules referenced in the JSON exist in modules table
// ---------------------------------------------------------------------------
const allModules = [...new Set(sortedGroups.map((g) => g.module))].sort();

lines.push("-- ============================================================================");
lines.push("-- Part 1: Upsert module entries");
lines.push("-- ============================================================================");
lines.push("");

for (const mod of allModules) {
  const name = mod.charAt(0).toUpperCase() + mod.slice(1);
  lines.push(
    `INSERT INTO modules (code, name) VALUES ('${mod}', '${name}')`
  );
  lines.push(
    `ON DUPLICATE KEY UPDATE name = VALUES(name), updated_at = CURRENT_TIMESTAMP;`
  );
  lines.push("");
}

// ---------------------------------------------------------------------------
// Step 2: Seed company-level module_roles for all entries
// ---------------------------------------------------------------------------

lines.push("-- ============================================================================");
lines.push("-- Part 2: Seed company-level module_roles for ALL roles × modules × resources");
lines.push("-- ============================================================================");
lines.push("");
lines.push("SET FOREIGN_KEY_CHECKS=0;");
lines.push("SET UNIQUE_CHECKS=0;");
lines.push("");

for (const group of sortedGroups) {
  const roleList = group.roleCodes
    .sort()
    .map((r) => `'${r}'`)
    .join(", ");

  lines.push(
    `-- ${group.module}.${group.resource} = ${group.mask} → ${group.roleCodes.sort().join(", ")}`
  );
  lines.push(
    `INSERT IGNORE INTO module_roles (company_id, role_id, module, resource, permission_mask)`
  );
  lines.push(
    `SELECT c.id AS company_id, r.id AS role_id, '${group.module}', '${group.resource}', ${group.mask}`
  );
  lines.push(`FROM companies c`);
  lines.push(`CROSS JOIN roles r`);
  lines.push(`WHERE r.code IN (${roleList});`);
  lines.push("");
}

lines.push("SET FOREIGN_KEY_CHECKS=1;");
lines.push("SET UNIQUE_CHECKS=1;");
lines.push("");

const output = lines.join("\n");

// ---------------------------------------------------------------------------
// Write output
// ---------------------------------------------------------------------------

if (outputPath) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, output, "utf-8");
  const sizeKB = (Buffer.byteLength(output) / 1024).toFixed(1);
  console.log(
    `Generated ${outputPath} (${sortedGroups.length} groups, ${sizeKB} KB)`
  );
} else {
  process.stdout.write(output);
}
